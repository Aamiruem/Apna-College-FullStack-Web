// In JavaScript, an API (Application Programming Interface) is a set of built-in functions and objects that let your code interact with the browser, server, or external services.

// 👉 Short answer:
// An API in JS allows JavaScript to communicate with other programs or services.

// 💡 Examples:

// Browser APIs → built into browsers

// fetch() → get data from a server

// localStorage → store data in the browser

// DOM API → manipulate HTML elements

// Third-party APIs → from external services

// Example: OpenWeather API for weather data

// Example: YouTube API for videos

// 🧠 In short:

// JavaScript APIs help your code connect, fetch, and use data or features from the browser or other web services.













