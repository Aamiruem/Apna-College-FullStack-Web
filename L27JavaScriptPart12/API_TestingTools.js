// 🧪 Testing API Requests

// When you test an API, you basically send requests (like GET, POST, PUT, DELETE) to an API URL
// and check if the response (data, status, and time) is correct.

// Example:
// Send a request to
// 👉 https://catfact.ninja/fact
// and check if it returns a random cat fact in JSON format.

// 🧰 1. Postman

// 🔹 Description:
// Postman is the most widely used API testing tool. It has a clean interface where you can easily create, send, and save API requests.

// 💡 Features:

// Send all types of HTTP requests (GET, POST, PUT, DELETE)

// View JSON responses clearly

// Add headers, body, and authorization tokens

// Save collections of APIs

// Automate API testing with scripts

// 🧩 Example:

// Open Postman

// Click New → Request

// Enter URL: https://dog.ceo/api/breeds/image/random

// Choose method: GET

// Click Send

// You’ll see a JSON response with a random dog image URL 🐶

// ⚙️ 2. Hoppscotch (previously Postwoman)

// 🔹 Description:
// Hoppscotch is a lightweight, open-source alternative to Postman.
// It runs directly in your browser (no installation needed).

// 💡 Features:

// Fast and simple web interface

// Test APIs directly in browser

// Supports REST, GraphQL, WebSocket

// Option to save and share requests

// Dark mode and minimal UI ✨

// 🌍 Website:
// https://hoppscotch.io

// 🧩 Example:

// Go to https://hoppscotch.io

// Paste the API URL — e.g. https://boredapi.com/api/activity

// Select method → GET

// Click Send

// You’ll see a JSON response like:

// {
//   "activity": "Go for a walk"
// }

// 🧠 In short:
// Tool	Type	Best For
// Postman	Desktop App	Full-featured API testing and automation
// Hoppscotch	Web App	Quick online API testing












